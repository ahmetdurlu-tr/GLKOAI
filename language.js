    const entries = [];
    const attributes = [];
    let current = 'en';
    function capture() {
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            const parent = node.parentElement;
            if (!parent || parent.closest('script, style, textarea, [contenteditable], #languageHelp, .sym-btn')) continue;
            // An option without a value attribute uses its displayed text as its value.
            if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) continue;
            const text = node.nodeValue;
            const trimmed = text.trim();
            if (Object.prototype.hasOwnProperty.call(words, trimmed)) entries.push({node, text, trimmed});
        }
        document.querySelectorAll('[title], [placeholder], [data-tooltip]').forEach(element => {
            for (const name of ['title', 'placeholder', 'data-tooltip']) {
                if (!element.hasAttribute(name)) continue;
                const value = element.getAttribute(name);
                if (Object.prototype.hasOwnProperty.call(words, value)) attributes.push({element, name, value});
            }
        });
    }
    function apply() {
        document.documentElement.lang = current;
        entries.forEach(({node, text, trimmed}) => {
            if (!node.isConnected) return;
            node.nodeValue = current === 'en' ? text.replace(trimmed, words[trimmed]) : text;
        });
        attributes.forEach(({element, name, value}) => {
            if (element.isConnected) element.setAttribute(name, current === 'en' ? words[value] : value);
        });
        const select = document.getElementById('languageSelect');
        if (select) select.value = current;
        const hint = document.getElementById('languageHelp');
        if (hint) hint.textContent = current === 'en' ? 'Preview: some screens, reports and messages remain in Turkish.' : 'Önizleme: bazı ekranlar, raporlar ve mesajlar Türkçe kalır.';
    }
    window.LanguageManager = {
        setLanguage(lang) {
            if (lang !== 'tr' && lang !== 'en') return;
            current = lang;
            try { localStorage.setItem('appLanguage', lang); } catch (_) {}
            apply();
            // Refresh displayed records without rewriting stored values.
            if (typeof renderList === 'function') renderList();
        },
        translate(value) {
            if (current !== 'en' || typeof value !== 'string') return value;
            if (Object.prototype.hasOwnProperty.call(words, value)) return words[value];
            let m;
            if ((m = value.match(/^"(.+)" listenizden silinsin mi\?$/))) return `Remove "${m[1]}" from your list?`;
            if ((m = value.match(/^"(.+)" aktivitesi silinsin mi\?$/))) return `Delete activity "${m[1]}"?`;
            if ((m = value.match(/^"(.+)" ilacını silmek istediğinize emin misiniz\?$/))) return `Delete medication "${m[1]}"?`;
            if ((m = value.match(/^"(.+)" silinsin mi\?$/))) return `Delete "${m[1]}"?`;
            if ((m = value.match(/^"(.+)" eklendi$/))) return `Added "${m[1]}"`;
            if ((m = value.match(/^"(.+)" ilacı güncellendi$/))) return `Medication "${m[1]}" updated`;
            if ((m = value.match(/^(\d+) yemek eklendi\.$/))) return `${m[1]} foods added.`;
            if ((m = value.match(/^(\d+) yemek güncellendi\.$/))) return `${m[1]} foods updated.`;
            if ((m = value.match(/^Alarm (.+) saatine (taşındı|eklendi)$/))) return m[2] === 'eklendi' ? `Reminder added for ${m[1]}` : `Reminder moved to ${m[1]}`;
            if (value.startsWith('Kayıt hatası: ')) return 'Save error: ' + value.slice('Kayıt hatası: '.length);
            return value;
        },
        get currentLang() { return current; }
    };
